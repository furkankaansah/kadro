function detect() {
  try {
    const saved = localStorage.getItem('kadro.lang');
    if (saved === 'tr' || saved === 'en') return saved;
  } catch {
    /* depolama kapalı olabilir */
  }
  return (navigator.language || 'tr').toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

let lang = detect();
document.documentElement.lang = lang;

export const getLang = () => lang;

export function setLang(next) {
  if (next !== 'tr' && next !== 'en') return;
  lang = next;
  try {
    localStorage.setItem('kadro.lang', next);
  } catch {
    /* yoksay */
  }
  document.documentElement.lang = next;
  window.dispatchEvent(new CustomEvent('kadro:lang'));
}

/** t('group.members', { a: 3, b: 5 }) — eksik anahtar önce İngilizceye, yoksa anahtarın kendisine düşer. */
export function t(key, vars) {
  let s = dict[lang][key] ?? dict.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : ''));
  return s;
}
